"""Offer letter PDF, standard library only (no extra dependency).

Uses the brand name and colours from shared/brand.json and is clearly marked
as a demo document. Text is limited to WinAnsi-safe characters ("INR", not the
rupee sign) so the built-in Helvetica font can show it.
"""

import io
from datetime import date

from core.brand import get_brand


def _hex(color: str) -> str:
    color = color.lstrip("#")
    r, g, b = (int(color[i : i + 2], 16) / 255 for i in (0, 2, 4))
    return f"{r:.3f} {g:.3f} {b:.3f}"


def _safe(text: str) -> str:
    text = str(text).encode("latin-1", "replace").decode("latin-1")
    return text.replace("\\", "\\\\").replace("(", "\\(").replace(")", "\\)")


def rupees(amount: int) -> str:
    """Indian digit grouping: 1250000 -> INR 12,50,000."""
    digits = str(int(amount))
    if len(digits) <= 3:
        return f"INR {digits}"
    head, tail = digits[:-3], digits[-3:]
    groups = []
    while len(head) > 2:
        groups.insert(0, head[-2:])
        head = head[:-2]
    if head:
        groups.insert(0, head)
    return "INR " + ",".join(groups) + "," + tail


def _wrap(text: str, width: int = 88) -> list[str]:
    words, lines, line = text.split(), [], ""
    for word in words:
        if len(line) + len(word) + 1 > width:
            lines.append(line)
            line = word
        else:
            line = f"{line} {word}".strip()
    if line:
        lines.append(line)
    return lines


def _long_date(value: str) -> str:
    try:
        return date.fromisoformat(value).strftime("%d %B %Y")
    except (TypeError, ValueError):
        return str(value)


def build_offer_pdf(
    *, candidate_name: str, job_title: str, data: dict, expires_on: str, issued_on: str
) -> bytes:
    brand = get_brand()
    colors = brand["colors"]
    employer = brand["employerName"]
    ops: list[str] = []

    def text(x, y, value, size=11, font="F1", color=colors["ink"]):
        ops.append(f"BT /{font} {size} Tf {_hex(color)} rg {x} {y} Td ({_safe(value)}) Tj ET")

    # Header band in the brand colour.
    ops.append(f"{_hex(colors['primary'])} rg 0 762 595 80 re f")
    text(48, 806, brand["name"], 20, "F2", "#FFFFFF")
    text(48, 784, f"{employer} - {brand['tagline']}", 10, "F1", "#FFFFFF")
    # Light diagonal watermark.
    ops.append(
        "BT /F2 40 Tf 0.900 0.900 0.900 rg 0.707 0.707 -0.707 0.707 110 200 Tm (DEMO DOCUMENT - NOT A "
        "REAL OFFER) Tj ET"
    )
    # Demo banner.
    ops.append(f"{_hex(colors['warningSoft'])} rg 48 716 499 30 re f")
    text(
        58,
        727,
        "Demo document: fictional company, fictional offer. Not a real offer of employment.",
        9.5,
        "F2",
        colors["warning"],
    )

    y = 684
    text(48, y, f"Date: {_long_date(issued_on)}")
    y -= 28
    text(48, y, f"Dear {candidate_name},", 12, "F2")
    y -= 22
    intro = (
        f"We are delighted to offer you the position of {data.get('designation', job_title)} at {employer}. "
        "This letter sets out the main terms of the offer."
    )
    for line in _wrap(intro):
        text(48, y, line)
        y -= 15
    y -= 10
    rows = [
        ("Designation", data.get("designation", job_title)),
        ("Department", data.get("department", "")),
        ("Location", data.get("location", "")),
        ("Reporting manager", data.get("reporting_manager_name", "")),
        ("Joining date", _long_date(data.get("joining_date", ""))),
        ("Fixed pay (annual)", rupees(data.get("fixed_pay", 0))),
        ("Variable pay (annual, target)", rupees(data.get("variable_pay", 0))),
    ]
    if data.get("joining_bonus"):
        rows.append(("Joining bonus (one time)", rupees(data["joining_bonus"])))
    total = int(data.get("fixed_pay", 0)) + int(data.get("variable_pay", 0))
    rows.append(("Total annual compensation", rupees(total)))
    for label, value in rows:
        ops.append(f"{_hex(colors['canvasDeep'])} rg 48 {y - 6} 499 0.6 re f")
        text(48, y, label, 10.5, "F2", colors["inkSoft"])
        text(260, y, str(value), 10.5)
        y -= 22
    y -= 8
    closing = (
        f"This offer is valid until {_long_date(expires_on)}. To accept, sign in to your candidate "
        "dashboard and "
        "type your full name as acknowledgement. Your typed name records that you accept; it is not a legal "
        "electronic signature. Final employment terms would be confirmed in an appointment letter."
    )
    for line in _wrap(closing):
        text(48, y, line)
        y -= 15
    y -= 20
    text(48, y, "Warm regards,")
    y -= 16
    text(48, y, f"Talent team, {employer}", 11, "F2")
    footer = (
        f"Generated by {brand['name']} for demonstration only. All people, companies and amounts are "
        "fictional."
    )
    text(48, 40, footer, 8, "F1", colors["muted"])

    stream = "\n".join(ops).encode("latin-1")
    title = _safe(f"Offer letter - {job_title} (demo)").encode("latin-1")
    objects = [
        b"<< /Type /Catalog /Pages 2 0 R >>",
        b"<< /Type /Pages /Kids [3 0 R] /Count 1 >>",
        b"<< /Type /Page /Parent 2 0 R /MediaBox [0 0 595 842] "
        b"/Resources << /Font << /F1 4 0 R /F2 5 0 R >> >> /Contents 6 0 R >>",
        b"<< /Type /Font /Subtype /Type1 /BaseFont /Helvetica /Encoding /WinAnsiEncoding >>",
        b"<< /Type /Font /Subtype /Type1 /BaseFont /Helvetica-Bold /Encoding /WinAnsiEncoding >>",
        b"<< /Length %d >>\nstream\n" % len(stream) + stream + b"\nendstream",
        b"<< /Title (" + title + b") /Producer (TalentPath demo) >>",
    ]
    out = io.BytesIO()
    out.write(b"%PDF-1.4\n%\xe2\xe3\xcf\xd3\n")
    offsets = []
    for number, body in enumerate(objects, start=1):
        offsets.append(out.tell())
        out.write(b"%d 0 obj\n" % number + body + b"\nendobj\n")
    xref = out.tell()
    out.write(b"xref\n0 %d\n0000000000 65535 f \n" % (len(objects) + 1))
    for offset in offsets:
        out.write(b"%010d 00000 n \n" % offset)
    out.write(
        b"trailer\n<< /Size %d /Root 1 0 R /Info 7 0 R >>\nstartxref\n%d\n%%%%EOF\n"
        % (len(objects) + 1, xref)
    )
    return out.getvalue()
