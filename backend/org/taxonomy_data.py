def skill_slug(name: str) -> str:
    value = name.lower()
    for old, new in (("c++", "cpp"), ("c#", "csharp"), (".net", "dotnet"), ("+", "plus"), ("#", "sharp")):
        value = value.replace(old, new)
    return slugify(value)


